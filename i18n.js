// Keep references to static text nodes so translating never replaces controls or their state.
const staticText = [];
const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest("script, style")) continue;
  const key = node.nodeValue.trim();
  if (key && Object.hasOwn(portuguese, key)) staticText.push({ node, key, before: node.nodeValue.match(/^\s*/)[0], after: node.nodeValue.match(/\s*$/)[0] });
}
const staticAttributes = [];
document.querySelectorAll("[aria-label], [placeholder], meta[name='description']").forEach(node => {
  for (const attribute of ["aria-label", "placeholder", "content"]) {
    if (node.hasAttribute(attribute)) staticAttributes.push({node, attribute, key: node.getAttribute(attribute)});
  }
});
function translatePage() {
  document.documentElement.lang = language;
  for (const {node, key, before, after} of staticText) node.nodeValue = before + t(key) + after;
  for (const {node, attribute, key} of staticAttributes) node.setAttribute(attribute, t(key));
  document.querySelector("#language").value = language;
}
